def get_glyph(name: str, size: int = 8) -> list[list[int]]:
    """Return the 2D pixel array for the given glyph and size (8 or 12)."""
    table = GLYPHS_12 if size == 12 else GLYPHS_8
    if name not in table:
        raise KeyError(f"Unknown glyph '{name}'. Available: {list(table.keys())}")
    return table[name]


def draw_glyph(
    draw: ImageDraw.ImageDraw,
    x: int,
    y: int,
    name: str,
    fill: Any,
    size: int = 8,
) -> None:
    """Draw a glyph onto an ImageDraw surface at pixel coordinates (x, y)."""
    matrix = get_glyph(name, size)
    for row_idx, row in enumerate(matrix):
        for col_idx, val in enumerate(row):
            if val:
                draw.point((x + col_idx, y + row_idx), fill=fill)


def glyph_to_ascii(name: str, size: int = 8) -> str:
    """Convert a glyph to an ASCII art string representation with '#' and '.'."""
    matrix = get_glyph(name, size)
    return "\n".join("".join("#" if val else "." for val in row) for row in matrix)


def glyph_image(
    name: str,
    fill: Any = (255, 255, 255),
    bg: Any = (0, 0, 0),
    size: int = 8,
) -> Image.Image:
    """Create a PIL Image of the glyph."""
    img = Image.new("RGB", (size, size), bg)
    d = ImageDraw.Draw(img)
    draw_glyph(d, 0, 0, name, fill=fill, size=size)
    return img
